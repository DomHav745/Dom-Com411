print("Which direction should I go?")
direction = input()
if direction == "up":
    print("I am moving in an upward direction")
elif direction == "left":
    print("I am moving in the left direction")
elif direction == "down":
    print("I am moving in a downward direction")
elif direction == "right":
    print("I am moving in the right direction")
else:
    print("I am not going anywhere")